--- Language code ("cs", "sk", "en") from KOReader's language setting.
function I18n.language()
    local lang = "en"
    if type(G_reader_settings) == "table" then
        local ok, value = pcall(G_reader_settings.readSetting, G_reader_settings, "language")
        if ok and type(value) == "string" then
            lang = value:sub(1, 2):lower()
        end
    end
    return TEXTS[lang] and lang or "en"
end

--- T("key", ...) -> text in the current language (string.format with the arguments).
function I18n.T(key, ...)
    local text = TEXTS[I18n.language()][key] or TEXTS.en[key] or key
    if select("#", ...) > 0 then
        return string.format(text, ...)
    end
    return text
end

